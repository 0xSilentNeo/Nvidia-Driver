#ifndef _LKPI_LINUX_NETDEV_FEATURES_H_
#define _LKPI_LINUX_NETDEV_FEATURES_H_
#include <linux/types.h>
typedef u64 netdev_features_t;
enum {
	NETIF_F_SG_BIT, NETIF_F_IP_CSUM_BIT, NETIF_F_HW_CSUM_BIT, NETIF_F_IPV6_CSUM_BIT,
	NETIF_F_HIGHDMA_BIT, NETIF_F_FRAGLIST_BIT, NETIF_F_HW_VLAN_CTAG_TX_BIT,
	NETIF_F_HW_VLAN_CTAG_RX_BIT, NETIF_F_RXCSUM_BIT, NETIF_F_RXHASH_BIT,
	NETIF_F_TSO_BIT, NETIF_F_GRO_BIT, NETIF_F_LRO_BIT, NETIF_F_RXFCS_BIT,
	NETIF_F_RXALL_BIT, NETIF_F_HW_TC_BIT, NETDEV_FEATURE_COUNT
};
#define __NETIF_F_BIT(bit) ((netdev_features_t)1 << (bit))
#define NETIF_F_SG		__NETIF_F_BIT(NETIF_F_SG_BIT)
#define NETIF_F_IP_CSUM		__NETIF_F_BIT(NETIF_F_IP_CSUM_BIT)
#define NETIF_F_HW_CSUM		__NETIF_F_BIT(NETIF_F_HW_CSUM_BIT)
#define NETIF_F_IPV6_CSUM	__NETIF_F_BIT(NETIF_F_IPV6_CSUM_BIT)
#define NETIF_F_HIGHDMA		__NETIF_F_BIT(NETIF_F_HIGHDMA_BIT)
#define NETIF_F_FRAGLIST	__NETIF_F_BIT(NETIF_F_FRAGLIST_BIT)
#define NETIF_F_RXCSUM		__NETIF_F_BIT(NETIF_F_RXCSUM_BIT)
#define NETIF_F_RXHASH		__NETIF_F_BIT(NETIF_F_RXHASH_BIT)
#define NETIF_F_TSO		__NETIF_F_BIT(NETIF_F_TSO_BIT)
#define NETIF_F_GRO		__NETIF_F_BIT(NETIF_F_GRO_BIT)
#define NETIF_F_LRO		__NETIF_F_BIT(NETIF_F_LRO_BIT)
#define NETIF_F_HW_TC		__NETIF_F_BIT(NETIF_F_HW_TC_BIT)
#define NETIF_F_CSUM_MASK	(NETIF_F_IP_CSUM | NETIF_F_HW_CSUM | NETIF_F_IPV6_CSUM)
#endif
