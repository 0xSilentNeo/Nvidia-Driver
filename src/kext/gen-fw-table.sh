# gen-fw-table.sh OUT_DIR [FIRMWARE_DIR [FILE ...]]
#
# Emits OUT_DIR/fw_blobs.S (the blobs via .incbin, in __TEXT,__const) and
# OUT_DIR/fw_table.c (the lkpi_fw_blobs[] table lkpi_os_firmware_load()
# consults before asking kernelmanagerd for a bundle resource).  FILE
# arguments are paths relative to FIRMWARE_DIR and are also the names the
# driver requests (e.g. mediatek/mt7925/WIFI_RAM_CODE_MT7925_1_1.bin).
# With no FILE arguments an empty table is produced.
set -eu
OUT=${1:?out dir}
FWDIR=${2:-}
shift $(( $# >= 2 ? 2 : $# ))
mkdir -p "$OUT"
S="$OUT/fw_blobs.S"
C="$OUT/fw_table.c"

{
	echo '/* generated by gen-fw-table.sh - do not edit */'
	echo '	.section __TEXT,__const'
	echo '	.p2align 4'
} > "$S.tmp"
{
	echo '/* generated by gen-fw-table.sh - do not edit */'
	echo 'struct lkpi_fw_blob { const char *name; const unsigned char *start; const unsigned char *end; };'
} > "$C.tmp"

i=0
for f in "$@"; do
	[ -f "$FWDIR/$f" ] || { echo "gen-fw-table: missing $FWDIR/$f" >&2; continue; }
	sym="lkpi_fw_blob_$i"
	{
		echo "	.globl _${sym}_start"
		echo "	.globl _${sym}_end"
		echo "_${sym}_start:"
		echo "	.incbin \"$FWDIR/$f\""
		echo "_${sym}_end:"
		echo "	.p2align 4"
	} >> "$S.tmp"
	{
		echo "extern const unsigned char ${sym}_start[], ${sym}_end[];"
	} >> "$C.tmp"
	i=$((i + 1))
done

{
	echo 'const struct lkpi_fw_blob lkpi_fw_blobs[] = {'
	j=0
	for f in "$@"; do
		[ -f "$FWDIR/$f" ] || continue
		echo "	{ \"$f\", lkpi_fw_blob_${j}_start, lkpi_fw_blob_${j}_end },"
		j=$((j + 1))
	done
	echo '	{ 0, 0, 0 },'
	echo '};'
	echo "const unsigned int lkpi_fw_blob_count = $i;"
} >> "$C.tmp"

mv "$S.tmp" "$S"
mv "$C.tmp" "$C"
echo "gen-fw-table: $i blob(s) -> $C"
