/*
 * lkpi_os_iokit.hpp - kext-internal view of the IOKit backend for lkpi/os.h.
 *
 * Shared between MT7925PCIe.cpp (the IOService) and lkpi_os_iokit.cpp (the
 * implementation of every lkpi_os_* function).  Nothing in here may include
 * a Linux header: the C++ side only ever sees lkpi/os.h and lkpi/runtime.h.
 */
#ifndef LKPI_OS_IOKIT_HPP
#define LKPI_OS_IOKIT_HPP

#include <IOKit/IOTypes.h>
#include <IOKit/IOLocks.h>
#include <lkpi/os.h>

class IOService;
class IOPCIDevice;
class IOWorkLoop;
class IOInterruptEventSource;
class IOMemoryMap;
class OSObject;

/* Compile-time knobs.  Everything here defaults to the conservative choice
 * that is known to build against the public Kernel.framework headers; flip
 * them once the symbol has been confirmed on the target SDK. */
#ifndef LKPI_OS_HAVE_THREAD_POLICY
#define LKPI_OS_HAVE_THREAD_POLICY 0		/* thread_policy_set() for realtime kthreads */
#endif
#ifndef LKPI_OS_HAVE_CPU_NUMBER
#define LKPI_OS_HAVE_CPU_NUMBER 0		/* cpu_number() (kern/cpu_number.h, kpi.unsupported) */
#endif
#ifndef LKPI_OS_HAVE_THREAD_BLOCK
#define LKPI_OS_HAVE_THREAD_BLOCK 0		/* thread_block(THREAD_CONTINUE_NULL) for yield */
#endif
#ifndef LKPI_OS_HAVE_MACH_CONTINUOUS_TIME
#define LKPI_OS_HAVE_MACH_CONTINUOUS_TIME 1	/* mach_continuous_time() (10.12+) */
#endif
#ifndef LKPI_OS_COHERENT_INHIBIT_CACHE
#if defined(__x86_64__)
#define LKPI_OS_COHERENT_INHIBIT_CACHE 0	/* x86 DMA is cache-coherent, like Linux WB */
#else
#define LKPI_OS_COHERENT_INHIBIT_CACHE 1	/* arm64: be conservative */
#endif
#endif
#ifndef LKPI_OS_PAGES_PHYS_MASK
/* Physical mask for lkpi_os_alloc_pages(): 32-bit, page aligned, so the
 * page-pool RX buffers never need an IODMACommand bounce on a machine
 * without a VT-d mapper.  MT7925 is a 32-bit DMA device. */
#define LKPI_OS_PAGES_PHYS_MASK 0x00000000FFFFF000ULL
#endif

#define LKPI_OS_MAX_BARS 6

/*
 * The opaque handle the C bus layer receives from lkpi_pci_attach().
 */
struct lkpi_os_pci {
	IOPCIDevice		*dev;		/* retained by MT7925PCIe */
	IOWorkLoop		*wl;		/* per-device interrupt workloop (retained) */
	IOService		*provider;	/* the MT7925PCIe instance */
	OSObject		*irq_owner;	/* LKPIEventOwner used as event-source owner */
	IOInterruptEventSource	*irq_src;
	lkpi_os_irq_fn		 irq_fn;
	void			*irq_arg;
	int			 irq_index;
	bool			 irq_msi;
	bool			 irq_enabled;
	IOMemoryMap		*bars[LKPI_OS_MAX_BARS];
	void			*priv;		/* C bus layer private pointer */
	IOLock			*lock;		/* protects irq_* and bars[] */
};

/* Allocate / free a handle.  The caller keeps its own references on the
 * IOPCIDevice and the workloop; the handle borrows them. */
lkpi_os_pci_t	lkpi_os_pci_create(IOPCIDevice *dev, IOWorkLoop *wl, IOService *provider);
void		lkpi_os_pci_destroy(lkpi_os_pci_t pci);

extern "C" {
/* Backend-wide start/stop (refcounted): creates the shared timer workloop,
 * the 10 ms jiffies tick, the thread table and the DMA registry.  Called by
 * MT7925PCIe::start()/stop() around lkpi_runtime_init()/fini(). */
int	lkpi_os_start(void);
void	lkpi_os_stop(void);

/* Firmware blobs linked into the kext binary (generated by gen-fw-table.sh
 * when EMBED_FIRMWARE=1).  Looked up before OSKextRequestResource because a
 * kext injected by OpenCore has no bundle on disk for kernelmanagerd to
 * read resources from. */
struct lkpi_fw_blob {
	const char		*name;	/* e.g. "mediatek/mt7925/WIFI_RAM_CODE_MT7925_1_1.bin" */
	const unsigned char	*start;
	const unsigned char	*end;
};
extern const struct lkpi_fw_blob lkpi_fw_blobs[];
extern const unsigned int lkpi_fw_blob_count;
}

#endif /* LKPI_OS_IOKIT_HPP */
