def strip_comments_and_strings(src: str) -> str:
    # Remove block comments, line comments, string and char literals.
    src = re.sub(r"/\*.*?\*/", " ", src, flags=re.S)
    src = re.sub(r"//[^\n]*", " ", src)
    src = re.sub(r'"(?:\\.|[^"\\\n])*"', '""', src)
    src = re.sub(r"'(?:\\.|[^'\\\n])*'", "''", src)
    return src


def collect_definitions(files):
    """Identifiers defined inside the tree: macros, functions, types, enums."""
    defs = set()
    types = set()
    for path in files:
        with open(path, encoding="utf-8", errors="replace") as fh:
            raw = fh.read()
        src = strip_comments_and_strings(raw)
        for m in re.finditer(r"^\s*#\s*define\s+([A-Za-z_]\w*)", src, re.M):
            defs.add(m.group(1))
        # Function definitions and prototypes start in column 0 in kernel
        # style ("static int foo(" or just "foo(" on a continuation line);
        # statements never do, so this separates definitions from calls.
        for m in re.finditer(r"^(?!return\b|else\b|goto\b)(?:[A-Za-z_\*][\w\*]*[ \t]+)*\**([A-Za-z_]\w*)\s*\(", src, re.M):
            defs.add(m.group(1))
        # DECLARE_EWMA(name, ...) generates ewma_<name>_{init,add,read}
        for m in re.finditer(r"\bDECLARE_EWMA\(\s*(\w+)", src):
            for suffix in ("init", "add", "read"):
                defs.add(f"ewma_{m.group(1)}_{suffix}")
        for m in re.finditer(r"\b(struct|union|enum)\s+([A-Za-z_]\w*)\s*\{", src):
            types.add(m.group(2))
        # opaque forward declarations count as provided types
        for m in re.finditer(r"^\s*struct\s+([A-Za-z_]\w*)\s*;", src, re.M):
            types.add(m.group(1))
        for m in re.finditer(r"\bDECLARE_EWMA\(\s*(\w+)", src):
            types.add(f"ewma_{m.group(1)}")
        # bitfield.h generates these with ____MAKE_OP
        if "____MAKE_OP" in src:
            for t in ("u8", "u16", "u32", "u64", "le16", "le32", "le64", "be16", "be32", "be64"):
                for op in ("encode_bits", "get_bits", "replace_bits"):
                    defs.add(f"{t}_{op}")
                defs.add(f"{t}p_replace_bits")
        for m in re.finditer(r"\btypedef\b[^;]*?\b([A-Za-z_]\w*)\s*;", src):
            types.add(m.group(1))
        # enumerators
        for m in re.finditer(r"\benum\b[^{;]*\{([^}]*)\}", src, re.S):
            for e in re.finditer(r"^\s*([A-Z_][A-Z0-9_]*)\b", m.group(1), re.M):
                defs.add(e.group(1))
    return defs, types


def collect_uses(files):
    calls = collections.defaultdict(set)   # symbol -> files
    struct_uses = collections.defaultdict(set)
    for path in files:
        with open(path, encoding="utf-8", errors="replace") as fh:
            src = strip_comments_and_strings(fh.read())
        base = os.path.relpath(path)
        for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", src):
            calls[m.group(1)].add(base)
        for m in re.finditer(r"\b(?:struct|union|enum)\s+([A-Za-z_]\w*)\b(?!\s*\{)", src):
            struct_uses[m.group(1)].add(base)
    return calls, struct_uses


def is_internal(sym: str) -> bool:
    return sym.startswith(INTERNAL_PREFIXES)


def bucket_for(sym: str) -> str:
    for name, rx in BUCKETS:
        if re.search(rx, sym):
            return name
    return "other"


# Provided by libkern / libc, not by a header we own.
LIBC_SYMBOLS = {
    "memcpy", "memset", "memmove", "memcmp", "strlen", "strcmp", "strncmp",
    "strcpy", "strncpy", "strcat", "strchr", "strrchr", "strstr", "strnlen",
    "strcasecmp", "strncasecmp", "snprintf", "vsnprintf", "sprintf", "printf",
    "vprintf", "sscanf", "panic", "abs",
}


def kpi_provides(kpi_dir):
    """Set of identifiers defined anywhere under the LinuxKPI include tree."""
    if not kpi_dir or not os.path.isdir(kpi_dir):
        return None
    files = []
    for root, _, names in os.walk(kpi_dir):
        for n in names:
            if n.endswith(".h"):
                files.append(os.path.join(root, n))
    defs, types = collect_definitions(files)
    return defs | types | LIBC_SYMBOLS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="src/mt76")
    ap.add_argument("--kpi", default="src/linuxkpi/include")
    ap.add_argument("--md", default="docs/LINUX_API_INVENTORY.md")
    args = ap.parse_args()

    files = []
    for root, _, names in os.walk(args.src):
        for n in names:
            if n.endswith((".c", ".h")):
                files.append(os.path.join(root, n))
    files.sort()

    defs, types = collect_definitions(files)
    calls, struct_uses = collect_uses(files)
    provided = kpi_provides(args.kpi)
    if provided is not None:
        provided = provided | {d for d in defs if d.startswith("ewma_")}

    external = {}
    for sym, users in calls.items():
        if sym in defs or sym in C_KEYWORDS or is_internal(sym):
            continue
        if re.fullmatch(r"[a-z]\w{0,2}", sym):  # loop vars like fn(
            continue
        external[sym] = users
    ext_types = {t: u for t, u in struct_uses.items() if t not in types and not is_internal(t)}

    by_bucket = collections.defaultdict(list)
    for sym in sorted(external):
        by_bucket[bucket_for(sym)].append(sym)

    total = len(external)
    have = sum(1 for s in external if provided and s in provided)

    out = []
    out.append("# Linux kernel API inventory for the vendored mt76 sources\n")
    out.append("Generated by `scripts/api-inventory.py`; do not edit by hand.\n")
    out.append(f"Source tree: `{args.src}` ({len(files)} files). "
               f"External function-like symbols: **{total}**"
               + (f", provided by `{args.kpi}`: **{have}** ({100*have//max(total,1)}%)." if provided is not None else "."))
    out.append("\nA symbol counts as *provided* when a definition with that name exists "
               "anywhere under the LinuxKPI include tree. Stubs count, so this measures "
               "compile coverage, not behavioural correctness.\n")
    out.append("| Subsystem | symbols | provided |\n|---|---:|---:|")
    for name, _ in BUCKETS + [("other", None)]:
        syms = by_bucket.get(name, [])
        if not syms:
            continue
        p = sum(1 for s in syms if provided and s in provided)
        out.append(f"| {name} | {len(syms)} | {p} |")

    for name, _ in BUCKETS + [("other", None)]:
        syms = by_bucket.get(name, [])
        if not syms:
            continue
        out.append(f"\n## {name}\n")
        out.append("| symbol | status | used by |\n|---|---|---|")
        for s in syms:
            st = "-" if provided is None else ("ok" if s in provided else "**missing**")
            users = sorted(external[s])
            shown = ", ".join(os.path.basename(u) for u in users[:4])
            if len(users) > 4:
                shown += f", +{len(users)-4}"
            out.append(f"| `{s}` | {st} | {shown} |")

    out.append("\n## External struct / union / enum tags\n")
    out.append("| tag | status | used by |\n|---|---|---|")
    for t in sorted(ext_types):
        st = "-" if provided is None else ("ok" if t in provided else "**missing**")
        users = sorted(ext_types[t])
        shown = ", ".join(os.path.basename(u) for u in users[:4])
        if len(users) > 4:
            shown += f", +{len(users)-4}"
        out.append(f"| `{t}` | {st} | {shown} |")

    os.makedirs(os.path.dirname(args.md), exist_ok=True)
    with open(args.md, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{total} external symbols, {len(ext_types)} external type tags -> {args.md}")
    if provided is not None:
        print(f"provided by KPI: {have}/{total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
