"""
Inventory of the Linux kernel API surface used by the vendored mt76 sources.

The LinuxKPI layer in src/linuxkpi has to provide every function, macro and
type the driver uses that the driver does not itself define.  This script
derives that list mechanically so the compatibility layer can be built and
tracked against the real driver rather than from memory.

It is deliberately regex based (no compiler needed): the point is a
reviewable checklist, not a perfect symbol table.

Usage:
    scripts/api-inventory.py [--src src/mt76] [--kpi src/linuxkpi/include]
                             [--md docs/LINUX_API_INVENTORY.md]

With --kpi, each symbol is also marked as provided or missing by grepping the
compatibility headers, which turns the document into a progress tracker.
"""
import argparse
import collections
import os
import re
import sys

C_KEYWORDS = {
    "if", "for", "while", "switch", "return", "sizeof", "do", "else", "case",
    "typeof", "__typeof__", "defined", "offsetof", "alignof", "__alignof__",
    "__attribute__", "__builtin_expect", "__builtin_constant_p",
    "__builtin_bswap16", "__builtin_bswap32", "__builtin_bswap64",
    "__builtin_offsetof", "__builtin_types_compatible_p", "__builtin_choose_expr",
    "__builtin_memcpy", "__builtin_memset", "__builtin_ffs", "__builtin_clz",
    "__builtin_ctz", "__builtin_popcount", "__builtin_unreachable",
    "__builtin_ffsll", "__builtin_clzll", "__builtin_ctzll", "__builtin_popcountll",
    "__builtin_bswap", "__asm__", "asm", "goto", "static", "const", "struct",
    "union", "enum", "void", "int", "char", "long", "short", "unsigned",
    "signed", "float", "double", "bool", "_Static_assert", "__extension__",
}

